//! Small macOS-specific helpers. Everything here degrades to a no-op elsewhere
//! so the rest of the app stays portable.

use std::path::Path;

/// The app that was in front when something was copied.
#[derive(Clone, Debug, Default)]
pub struct SourceApp {
    pub bundle_id: String,
    pub name: String,
}

/// The pasteboard's change counter. It goes up on every copy (even when the
/// same thing is copied twice), so polling it is cheap and exact.
/// `None` where the platform has no such counter.
#[cfg(target_os = "macos")]
pub fn change_count() -> Option<i64> {
    use objc2_app_kit::NSPasteboard;
    Some(NSPasteboard::generalPasteboard().changeCount() as i64)
}

#[cfg(not(target_os = "macos"))]
pub fn change_count() -> Option<i64> {
    None
}

/// True when the pasteboard is marked concealed/transient by the app that put
/// it there (password managers do this, see nspasteboard.org). We never record
/// such clips.
#[cfg(target_os = "macos")]
pub fn is_sensitive() -> bool {
    use objc2_app_kit::NSPasteboard;
    const MARKS: [&str; 3] = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ];
    let Some(types) = NSPasteboard::generalPasteboard().types() else {
        return false;
    };
    types
        .iter()
        .any(|t| MARKS.contains(&t.to_string().as_str()))
}

#[cfg(not(target_os = "macos"))]
pub fn is_sensitive() -> bool {
    false
}

/// The frontmost app, or `None` if it is ClipVault itself.
#[cfg(target_os = "macos")]
pub fn frontmost_app() -> Option<SourceApp> {
    use objc2_app_kit::NSWorkspace;
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    if app.processIdentifier() as u32 == std::process::id() {
        return None;
    }
    Some(SourceApp {
        bundle_id: app
            .bundleIdentifier()
            .map(|s| s.to_string())
            .unwrap_or_default(),
        name: app
            .localizedName()
            .map(|s| s.to_string())
            .unwrap_or_default(),
    })
}

#[cfg(not(target_os = "macos"))]
pub fn frontmost_app() -> Option<SourceApp> {
    None
}

/// Hide the whole app so macOS gives focus back to the app you were using;
/// without this, ⌘V after picking a clip would go to ClipVault itself.
/// Must be called on the main thread (the UI's update loop is).
#[cfg(target_os = "macos")]
pub fn hide_app() {
    use objc2::MainThreadMarker;
    use objc2_app_kit::NSApplication;
    if let Some(mtm) = MainThreadMarker::new() {
        NSApplication::sharedApplication(mtm).hide(None);
    }
}

#[cfg(not(target_os = "macos"))]
pub fn hide_app() {}

#[cfg(target_os = "macos")]
mod ffi {
    use std::ffi::c_void;

    #[link(name = "ApplicationServices", kind = "framework")]
    extern "C" {
        pub fn AXIsProcessTrustedWithOptions(options: *const c_void) -> bool;
    }

    #[link(name = "CoreGraphics", kind = "framework")]
    extern "C" {
        pub fn CGEventSourceCreate(state: i32) -> *mut c_void;
        pub fn CGEventCreateKeyboardEvent(
            source: *mut c_void,
            keycode: u16,
            key_down: bool,
        ) -> *mut c_void;
        pub fn CGEventSetFlags(event: *mut c_void, flags: u64);
        pub fn CGEventPost(tap: u32, event: *mut c_void);
    }

    #[link(name = "CoreFoundation", kind = "framework")]
    extern "C" {
        pub fn CFRelease(cf: *const c_void);
    }

    pub const HID_SYSTEM_STATE: i32 = 1;
    pub const HID_EVENT_TAP: u32 = 0;
    pub const FLAG_COMMAND: u64 = 0x0010_0000;
    pub const KEY_V: u16 = 9; // kVK_ANSI_V
}

/// Whether macOS lets us send keystrokes (System Settings → Privacy &
/// Security → Accessibility). With `prompt`, macOS shows its permission
/// dialog if we are not allowed yet.
#[cfg(target_os = "macos")]
pub fn accessibility_trusted(prompt: bool) -> bool {
    use objc2::runtime::AnyObject;
    use objc2_foundation::{NSDictionary, NSNumber, NSString};
    let key = NSString::from_str("AXTrustedCheckOptionPrompt");
    let value = NSNumber::new_bool(prompt);
    let opts = NSDictionary::<NSString, AnyObject>::from_slices(&[&*key], &[&*value]);
    // NSDictionary is toll-free bridged with CFDictionary.
    unsafe { ffi::AXIsProcessTrustedWithOptions(&*opts as *const _ as *const _) }
}

#[cfg(not(target_os = "macos"))]
pub fn accessibility_trusted(_prompt: bool) -> bool {
    false
}

/// Press ⌘V in whatever app is frontmost. Needs Accessibility permission;
/// silently does nothing without it.
#[cfg(target_os = "macos")]
pub fn send_paste() {
    use ffi::*;
    unsafe {
        let source = CGEventSourceCreate(HID_SYSTEM_STATE);
        for down in [true, false] {
            let ev = CGEventCreateKeyboardEvent(source, KEY_V, down);
            if ev.is_null() {
                continue;
            }
            CGEventSetFlags(ev, FLAG_COMMAND);
            CGEventPost(HID_EVENT_TAP, ev);
            CFRelease(ev);
        }
        if !source.is_null() {
            CFRelease(source);
        }
    }
}

#[cfg(not(target_os = "macos"))]
pub fn send_paste() {}

/// Bring our window to the front on the current Space, even when launched as
/// a background (no Dock icon) app. Main thread only.
#[cfg(target_os = "macos")]
pub fn activate_window() {
    use objc2::MainThreadMarker;
    use objc2_app_kit::{NSApplication, NSWindowCollectionBehavior};
    let Some(mtm) = MainThreadMarker::new() else {
        return;
    };
    let app = NSApplication::sharedApplication(mtm);
    app.unhide(None);
    #[allow(deprecated)]
    app.activateIgnoringOtherApps(true);
    for window in app.windows().iter() {
        window.setCollectionBehavior(
            window.collectionBehavior() | NSWindowCollectionBehavior::MoveToActiveSpace,
        );
        window.makeKeyAndOrderFront(None);
        window.orderFrontRegardless();
    }
}

#[cfg(not(target_os = "macos"))]
pub fn activate_window() {}

/// Open a URL in the default browser.
pub fn open_url(url: &str) {
    #[cfg(target_os = "macos")]
    {
        let _ = std::process::Command::new("open").arg(url).spawn();
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = url;
    }
}

/// Show a file in Finder.
pub fn reveal(path: &Path) {
    #[cfg(target_os = "macos")]
    {
        let _ = std::process::Command::new("open")
            .arg("-R")
            .arg(path)
            .spawn();
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = path;
    }
}
